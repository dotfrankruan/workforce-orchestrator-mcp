import { spawn, execFileSync, type ChildProcess } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import type {
  WorkerBackend,
  WorkerBackendHandle,
  BackendStartOptions,
  BackendEvents,
  BackendMetadata,
  BackendModelEntry,
  BackendRuntimeInfo,
} from './types.js';
import type { WorkerEvent } from './events.js';
import { normalizeDshEvent } from './events.js';
import type { DshEvent } from '../parser.js';

export interface DshBackendOptions {
  dshBin: string;
  profile: string;
  /** Default model for every run (per-task `model` still wins). */
  model?: string | undefined;
  /** Provider id that owns the model (e.g. kimi-coding). */
  provider?: string | undefined;
  /** Reasoning effort passed to the runtime (e.g. max). */
  reasoningEffort?: string | undefined;
}

/** Raw selection parsed from `dsh --dump-config` (the profile's own default). */
export interface DshSelection {
  provider?: string | undefined;
  model?: string | undefined;
  reasoningEffort?: string | undefined;
}

export interface DshDumpConfig {
  models: BackendModelEntry[];
  default: DshSelection;
}

const MODEL_PATCH_FILENAME = 'dsh-model.yml';
const RUNTIME_CACHE_MS = 30_000;

/** Quote a YAML scalar only when needed (model ids/providers are usually plain). */
function yamlScalar(value: string): string {
  return /^[A-Za-z0-9._-]+$/.test(value) ? value : JSON.stringify(value);
}

/**
 * Parse `dsh --dump-config --profile <p>` output (YAML entry list) enough to
 * discover: (a) models per provider from the llm-pi-ai entry, (b) the
 * agent-default-model selection. Returns null when neither is present.
 *
 * Deliberately a focused line scanner, not a YAML parser: the dump format is
 * generated by dsh itself and stable, and a failed parse degrades to
 * "unknown" instead of inventing data.
 */
export function parseDshDumpConfig(text: string): DshDumpConfig | null {
  const models: BackendModelEntry[] = [];
  const def: DshSelection = {};
  let entry: string | null = null;
  let inProviders = false;
  let currentProvider: string | null = null;
  let inModels = false;
  let sawSomething = false;

  const lines = text.split('\n');
  for (const line of lines) {
    const top = /^- id:\s*'?([A-Za-z0-9_.:-]+)'?\s*$/.exec(line);
    if (top) {
      entry = top[1]!;
      inProviders = false;
      currentProvider = null;
      inModels = false;
      continue;
    }
    if (line.startsWith('# ==')) {
      entry = null;
      inProviders = false;
      inModels = false;
      continue;
    }

    if (entry === 'llm-pi-ai') {
      if (/^ {4}providers:\s*$/.test(line)) {
        inProviders = true;
        continue;
      }
      const provider = /^ {6}([A-Za-z0-9_.-]+):\s*$/.exec(line);
      if (inProviders && provider) {
        currentProvider = provider[1]!;
        inModels = false;
        continue;
      }
      if (inProviders && /^ {8}models:\s*$/.test(line)) {
        inModels = true;
        continue;
      }
      if (inModels) {
        const modelId = /^ {10}- id:\s*'?([^'\s]+)'?\s*$/.exec(line);
        if (modelId && currentProvider) {
          models.push({ provider: currentProvider, id: modelId[1]! });
          sawSomething = true;
          continue;
        }
        const modelName = /^ {12}name:\s*'?(.+?)'?\s*$/.exec(line);
        if (modelName && models.length > 0) {
          const last = models[models.length - 1]!;
          if (!last.name) last.name = modelName[1]!;
          continue;
        }
        // Any other line at <= provider indent ends the models list.
        if (/^ {0,8}\S/.test(line)) {
          inModels = false;
        }
      }
      continue;
    }

    if (entry === 'agent-default-model') {
      const field = /^ {4}(provider|model|reasoningEffort):\s*'?([^'\s#]+)'?\s*$/.exec(line);
      if (field) {
        const key = field[1]!;
        const value = field[2]!;
        if (key === 'provider') def.provider = value;
        else if (key === 'model') def.model = value;
        else def.reasoningEffort = value;
        sawSomething = true;
      }
      continue;
    }
  }

  if (!sawSomething) return null;
  return { models, default: def };
}

/** Generate the `--patch` overlay that replaces the agent-default-model entry. */
export function buildModelPatch(selection: { provider: string; model: string; reasoningEffort?: string | undefined }): string {
  const lines = [
    '# Generated by Workforce Orchestrator for a single worker run.',
    '# Overrides the profile default model; safe to delete.',
    '- id: agent-default-model',
    '  config:',
    `    provider: ${yamlScalar(selection.provider)}`,
    `    model: ${yamlScalar(selection.model)}`,
  ];
  if (selection.reasoningEffort) lines.push(`    reasoningEffort: ${yamlScalar(selection.reasoningEffort)}`);
  return lines.join('\n') + '\n';
}

/**
 * Runs DeepSeek Harness as the worker runtime:
 *
 *   /usr/local/bin/dsh --profile headless --patch <model.yml> --json "<prompt>"
 *
 * Model selection: each run may pin a model (per-task `model`, backend config
 * `backends.dsh.model`, or `WORKFORCE_DSH_MODEL`). Because the headless app has
 * no --model flag, this is applied with the launcher's documented `--patch`
 * overlay, which replaces the profile's `agent-default-model` entry (provider,
 * model, reasoningEffort). Base values come from `dsh --dump-config` (facts,
 * local only, never the network). Nothing is written unless an override is
 * actually requested.
 *
 * Durability by construction: the child's stdout/stderr are redirected
 * DIRECTLY to the durable log files (stdout.jsonl / stderr.log), never
 * through a pipe owned by this process — so the worker keeps writing even if
 * the supervisor dies. The supervisor parses the file via its tailer
 * (reattach path and live path share that machinery). Exit codes come from
 * the ChildProcess handle while attached; after a reattach they are
 * unavailable and left null (never fabricated).
 *
 * Always spawned with an argv array — never a shell string. Credentials are
 * left to dsh itself (~/.dsh/.env); this process never reads or forwards them.
 */
export class DshBackend implements WorkerBackend {
  readonly id = 'dsh';
  readonly displayName = 'DeepSeek Harness';
  readonly capabilities = {
    modelSelection: true,
    continuation: true,
    durableReattach: true,
    structuredEvents: true,
    usageReporting: true,
    toolCallEvents: true,
    artifacts: true,
  } as const;
  /** Marker expected in the worker process command line (reattach identity). */
  readonly processMarker = 'dsh';
  /** stdout/stderr go straight to files; the supervisor tails them. */
  readonly durableStdout = true;

  private versionCache: string | null | undefined;
  private runtimeCache: { at: number; dump: DshDumpConfig | null } | null = null;

  constructor(private opts: DshBackendOptions) {}

  normalizeEvent(raw: DshEvent): WorkerEvent[] {
    return normalizeDshEvent(raw);
  }

  /** Local availability only: executable exists and is runnable. No API calls. */
  isAvailable(): boolean {
    try {
      fs.accessSync(this.opts.dshBin, fs.constants.X_OK);
      return true;
    } catch {
      return false;
    }
  }

  private version(): string | null {
    if (this.versionCache !== undefined) return this.versionCache;
    try {
      const out = execFileSync(this.opts.dshBin, ['--version'], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 5000,
      }).trim();
      this.versionCache = out || null;
    } catch {
      this.versionCache = null;
    }
    return this.versionCache;
  }

  /** Raw profile default from `dsh --dump-config` (cached ~30s). */
  private profileDump(): DshDumpConfig | null {
    const now = Date.now();
    if (this.runtimeCache && now - this.runtimeCache.at < RUNTIME_CACHE_MS) return this.runtimeCache.dump;
    let dump: DshDumpConfig | null = null;
    try {
      const out = execFileSync(this.opts.dshBin, ['--profile', this.opts.profile, '--dump-config'], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 15000,
      });
      dump = parseDshDumpConfig(out);
    } catch {
      dump = null;
    }
    this.runtimeCache = { at: now, dump };
    return dump;
  }

  /** Configured default applied on top of the profile's own default. */
  private configuredSelection(): DshSelection {
    return {
      provider: this.opts.provider,
      model: this.opts.model,
      reasoningEffort: this.opts.reasoningEffort,
    };
  }

  private mergeSelection(base: DshSelection, over: DshSelection): DshSelection {
    return {
      provider: over.provider ?? base.provider,
      model: over.model ?? base.model,
      reasoningEffort: over.reasoningEffort ?? base.reasoningEffort,
    };
  }

  /** Facts only: runtime version + the effective default provider/model. */
  metadata(): BackendMetadata {
    const effective = this.mergeSelection(this.profileDump()?.default ?? {}, this.configuredSelection());
    return {
      runtime: { name: 'DeepSeek Harness', version: this.version() ?? undefined },
      provider: { name: effective.provider, model: effective.model },
    };
  }

  inspectRuntime(): BackendRuntimeInfo | null {
    const dump = this.profileDump();
    if (!dump) return null;
    return {
      models: dump.models,
      default: this.mergeSelection(dump.default, this.configuredSelection()),
    };
  }

  /**
   * Resolve the selection for one run and return the patch file path to pass
   * via --patch, or null when the profile default already matches.
   */
  private prepareModelPatch(opts: BackendStartOptions): string | null {
    const configured = this.configuredSelection();
    const overrideRequested =
      opts.model !== undefined ||
      configured.model !== undefined ||
      configured.provider !== undefined ||
      configured.reasoningEffort !== undefined;
    if (!overrideRequested) return null;

    const dump = this.profileDump();
    const raw: DshSelection = dump?.default ?? {};
    const effective = this.mergeSelection(this.mergeSelection(raw, configured), { model: opts.model });

    const matchesProfile =
      dump !== null &&
      effective.provider === raw.provider &&
      effective.model === raw.model &&
      (effective.reasoningEffort ?? null) === (raw.reasoningEffort ?? null);
    if (matchesProfile) return null;

    if (!effective.model) {
      throw new Error('cannot select a model: no model resolved (profile default unknown and backends.dsh.model unset)');
    }
    if (!effective.provider) {
      throw new Error(
        `cannot apply model ${JSON.stringify(effective.model)}: dsh provider unknown ` +
          `(dsh --dump-config failed and backends.dsh.provider is unset)`,
      );
    }

    const patchPath = path.join(path.dirname(opts.stdoutPath), MODEL_PATCH_FILENAME);
    fs.writeFileSync(
      patchPath,
      buildModelPatch({
        provider: effective.provider,
        model: effective.model,
        ...(effective.reasoningEffort ? { reasoningEffort: effective.reasoningEffort } : {}),
      }),
      'utf8',
    );
    return patchPath;
  }

  start(opts: BackendStartOptions, events: BackendEvents): WorkerBackendHandle {
    let patchPath: string | null;
    try {
      patchPath = this.prepareModelPatch(opts);
    } catch (err) {
      queueMicrotask(() => {
        events.onSpawnError?.(err as Error);
        events.onExit(null, null);
      });
      return new NullHandle();
    }

    const args = ['--profile', this.opts.profile];
    if (patchPath) args.push('--patch', patchPath);
    args.push('--json');
    if (opts.sessionId) {
      args.push('--session-id', opts.sessionId);
    }
    // Note: our prompts always start with "You are" / "The supervising",
    // never with "-", so no option/operand separator is needed (and dsh does
    // not document one).
    args.push(opts.prompt);

    let outFd: number;
    let errFd: number;
    let child: ChildProcess;
    try {
      outFd = fs.openSync(opts.stdoutPath, 'a');
      errFd = fs.openSync(opts.stderrPath, 'a');
      child = spawn(this.opts.dshBin, args, {
        cwd: opts.cwd,
        env: process.env,
        stdio: ['ignore', outFd, errFd],
      });
    } catch (err) {
      queueMicrotask(() => {
        events.onSpawnError?.(err as Error);
        events.onExit(null, null);
      });
      return new NullHandle();
    }

    const closeFds = () => {
      try { fs.closeSync(outFd); } catch { /* ignore */ }
      try { fs.closeSync(errFd); } catch { /* ignore */ }
    };

    let exited = false;
    child.on('error', (err) => {
      if (exited) return;
      exited = true;
      closeFds();
      events.onSpawnError?.(err);
      events.onExit(null, null);
    });
    child.on('close', (code, signal) => {
      if (exited) return;
      exited = true;
      closeFds();
      events.onExit(code, signal);
    });

    return new DshHandle(child, () => exited);
  }
}

class NullHandle implements WorkerBackendHandle {
  readonly pid = null;
  async terminate(): Promise<void> {}
}

class DshHandle implements WorkerBackendHandle {
  private termPromise: Promise<void> | null = null;

  constructor(
    private child: ChildProcess,
    private isExited: () => boolean,
  ) {}

  get pid(): number | null {
    return this.child.pid ?? null;
  }

  terminate(graceMs: number): Promise<void> {
    if (this.termPromise) return this.termPromise;
    this.termPromise = this.doTerminate(graceMs);
    return this.termPromise;
  }

  private doTerminate(graceMs: number): Promise<void> {
    return new Promise((resolve) => {
      if (this.isExited() || this.child.exitCode !== null || this.child.signalCode !== null) {
        resolve();
        return;
      }
      let resolved = false;
      const done = () => {
        if (!resolved) {
          resolved = true;
          resolve();
        }
      };
      const killTimer = setTimeout(() => {
        try {
          this.child.kill('SIGKILL');
        } catch {
          /* already gone */
        }
        setTimeout(done, 200).unref();
      }, graceMs);
      killTimer.unref();

      this.child.once('close', () => {
        clearTimeout(killTimer);
        done();
      });

      try {
        this.child.kill('SIGTERM');
      } catch {
        clearTimeout(killTimer);
        done();
      }
    });
  }
}
